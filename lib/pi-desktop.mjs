// PI-Desktop 的热切通道：它不再扫 ~/.pi/agent/extensions，扩展只能由插件贡献。
// 所以「/purge + 每轮读 state.json」这条只能做成一个 imported 插件：
//   <dataDir>/plugins/imported/agent-purge/{manifest.json,main.cjs,src/agent-purge.ts}
// 并在 <dataDir>/plugins/registry.json 里登记（source=dev，走它的热重载路径）。
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { extensionSource } from "./extension.mjs";

export const PLUGIN_ID = "imported.agent-purge";
const PLUGIN_DIR = "agent-purge";
const WRAPPER = "// Generated by PI-Desktop: declarative skills and/or agent extensions.\nmodule.exports = {};\n";
const MANIFEST = {
	schemaVersion: 1,
	id: PLUGIN_ID,
	name: "agent-purge",
	version: "0.0.0",
	description: "agent-purge persona extension（每轮读 state.json，/purge 热切换）",
	main: "main.cjs",
	permissions: ["agent.extension"],
	contributes: { agentExtensions: ["src/agent-purge.ts"] },
};

export function piDesktopDataDir() {
	return process.env.PI_DESKTOP_DATA_DIR?.trim() || join(homedir(), ".pi-desktop");
}
export const pluginDir = () => join(piDesktopDataDir(), "plugins", "imported", PLUGIN_DIR);
export const registryFile = () => join(piDesktopDataDir(), "plugins", "registry.json");

function readRegistry() {
	try {
		const parsed = JSON.parse(readFileSync(registryFile(), "utf8"));
		return Array.isArray(parsed) ? parsed : null;
	} catch {
		return null;
	}
}

export function probePlugin() {
	if (!existsSync(join(pluginDir(), "manifest.json"))) return false;
	const registry = readRegistry();
	return Boolean(registry?.some((p) => p?.id === PLUGIN_ID && p.enabled));
}

export function installPlugin(root) {
	const dir = pluginDir();
	mkdirSync(join(dir, "src"), { recursive: true });
	writeFileSync(join(dir, "src", "agent-purge.ts"), extensionSource(root, "pi-desktop"), "utf8");
	writeFileSync(join(dir, "main.cjs"), WRAPPER, "utf8");
	writeFileSync(join(dir, "manifest.json"), JSON.stringify(MANIFEST, null, 2) + "\n", "utf8");

	const registry = readRegistry();
	if (!registry) {
		return { error: `读不到插件登记表（${registryFile()}）；先在 PI-Desktop 里装任意一个插件再试` };
	}
	const entry = {
		id: PLUGIN_ID,
		name: "agent-purge",
		version: "0.0.0",
		enabled: true,
		scope: { mode: "global", projects: [] },
		source: "dev",
		status: "ready",
		permissions: ["agent.extension"],
		path: dir,
		capabilities: [],
		description: MANIFEST.description,
		author: "agent-purge",
		installedAt: new Date().toISOString(),
		updatedAt: new Date().toISOString(),
	};
	const index = registry.findIndex((p) => p?.id === PLUGIN_ID);
	if (index >= 0) registry[index] = { ...registry[index], ...entry, installedAt: registry[index].installedAt ?? entry.installedAt };
	else registry.push(entry);
	writeFileSync(registryFile(), JSON.stringify(registry, null, 2) + "\n", "utf8");
	return { file: join(dir, "src", "agent-purge.ts"), note: "插件已登记；重启一次 PI-Desktop 后生效，之后 /purge 与换人设都在会话内热切换" };
}

export function uninstallPlugin() {
	const removed = [];
	const registry = readRegistry();
	if (registry) {
		const next = registry.filter((p) => p?.id !== PLUGIN_ID);
		if (next.length !== registry.length) {
			writeFileSync(registryFile(), JSON.stringify(next, null, 2) + "\n", "utf8");
			removed.push("registry.json 里的 agent-purge 条目");
		}
	}
	const dir = pluginDir();
	if (existsSync(dir)) {
		try {
			const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8"));
			if (manifest?.id === PLUGIN_ID) {
				rmSync(dir, { recursive: true, force: true });
				removed.push(dir);
			}
		} catch {
			/* 不是我们的目录就不动 */
		}
	}
	return { removed };
}
